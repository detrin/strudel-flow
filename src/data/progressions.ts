import type { Bars } from '@/lib/chords/theory';

/**
 * Chord progressions and the feelings they usually carry for Western
 * listeners. These are learned conventions, not laws (Smit et al. 2022,
 * PLOS ONE); what moves people most is expectation: what the chords make
 * them predict, and whether it comes, is delayed, or swerves (Meyer 1956;
 * Huron 2006; Cheung et al. 2019, Current Biology). Numerals are relative
 * to the chosen key's tonic: a minor progression starts on i.
 */
export type Progression = {
  id: string;
  name: string;
  /** Bars of Roman numerals (see lib/chords/theory). */
  bars: Bars;
  /** The usual feeling, in a few words. */
  feeling: string;
  /** Why it feels so, in a sentence. */
  why: string;
  /** Feelings, to filter by. */
  tags: string[];
  /** Where it is heard: genres and kinds of music. */
  style: string[];
  source: { label: string; url: string };
};

const WIKI = 'https://en.wikipedia.org/wiki/';
const wiki = (label: string, page = label.replace(/ /g, '_')) => ({
  label,
  url: WIKI + page,
});

/** "I II IV bVI", two chords in a bar as "bVI+bVII". */
const bars = (text: string): Bars =>
  text.split(/\s+/).map((bar) => bar.split('+'));

const entry = (
  id: string,
  name: string,
  numerals: string,
  feeling: string,
  why: string,
  tags: string[],
  style: string[],
  source: { label: string; url: string },
): Progression => ({
  id,
  name,
  bars: bars(numerals),
  feeling,
  why,
  tags,
  style,
  source,
});

